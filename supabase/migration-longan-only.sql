-- ตัดพืชอื่นออกจากระบบ เหลือ "ลำไย" กับระยะการดูแล 12 ระยะเท่านั้น
-- รันหลัง migration-cultivation-stages.sql และ migration-longan-product-catalog.sql
-- ============================================================

begin;

-- ------------------------------------------------------------
-- 1) ปลดล็อก constraint เดิมชั่วคราว เพื่อแปลงข้อมูลเก่าได้
-- ------------------------------------------------------------
alter table public.cultivations drop constraint if exists cultivations_stage_check;

-- ------------------------------------------------------------
-- 2) แปลงระยะแบบเก่า (5 ช่วงทั่วไป) → ระยะลำไยที่ใกล้เคียงที่สุด
--    เตรียมดิน       → เตรียมต้นหลังเก็บเกี่ยว
--    ปลูก            → แตกใบอ่อน ใบแรก
--    ดูแล/บำรุง      → แตกใบอ่อน ใบสอง
--    ออกดอก/ติดผล    → ดอกบาน
--    เก็บเกี่ยว      → ก่อนเก็บ
-- ------------------------------------------------------------
update public.cultivations
set stage = case stage
  when 'เตรียมดิน'      then 'เตรียมต้นหลังเก็บเกี่ยว'
  when 'ปลูก'           then 'แตกใบอ่อน ใบแรก'
  when 'ดูแล/บำรุง'     then 'แตกใบอ่อน ใบสอง'
  when 'ออกดอก/ติดผล'   then 'ดอกบาน'
  when 'เก็บเกี่ยว'     then 'ก่อนเก็บ'
  else stage
end
where stage in ('เตรียมดิน', 'ปลูก', 'ดูแล/บำรุง', 'ออกดอก/ติดผล', 'เก็บเกี่ยว');

-- กันข้อมูลแปลกปลอม: ถ้ายังมี stage ที่ไม่อยู่ใน 12 ระยะ ให้ตั้งเป็นระยะแรก
update public.cultivations
set stage = 'เตรียมต้นหลังเก็บเกี่ยว'
where stage not in (
  'เตรียมต้นหลังเก็บเกี่ยว','แตกใบอ่อน ใบแรก','แตกใบอ่อน ใบสอง','ราดสาร',
  'เปิดตาดอก','ยืดช่อดอก','บำรุงช่อดอก','ดอกบาน',
  'ลูกเล็ก','ลูกมะเขือพวง','ลูกแก้ว','ก่อนเก็บ'
);

-- ------------------------------------------------------------
-- 3) constraint ใหม่ — รับได้เฉพาะ 12 ระยะลำไย
-- ------------------------------------------------------------
alter table public.cultivations
  alter column stage set default 'เตรียมต้นหลังเก็บเกี่ยว';

alter table public.cultivations
  add constraint cultivations_stage_check
  check (
    stage in (
      'เตรียมต้นหลังเก็บเกี่ยว',
      'แตกใบอ่อน ใบแรก',
      'แตกใบอ่อน ใบสอง',
      'ราดสาร',
      'เปิดตาดอก',
      'ยืดช่อดอก',
      'บำรุงช่อดอก',
      'ดอกบาน',
      'ลูกเล็ก',
      'ลูกมะเขือพวง',
      'ลูกแก้ว',
      'ก่อนเก็บ'
    )
  );

-- ------------------------------------------------------------
-- 4) ทำชื่อระยะใน crop_stages ให้ตรงกับที่แอปใช้ (ตัดวงเล็บอธิบายออก)
-- ------------------------------------------------------------
update public.crop_stages
set name = 'ราดสาร',
    description = coalesce(description, 'ช่วงเวลา: กรอบ 10 วัน (สารควบคุมการออกดอก)')
where id = 'stage_04';

-- ------------------------------------------------------------
-- 5) เติม stage_id ให้ตรงกับชื่อระยะ (ทุกแถว)
-- ------------------------------------------------------------
update public.cultivations c
set stage_id = s.id
from public.crop_stages s
where s.name = c.stage;

-- current_sequence ต้องไม่เป็น null เพื่อให้ view คำนวณรอบถัดไปได้
update public.cultivations
set current_sequence = 0
where current_sequence is null;

-- ------------------------------------------------------------
-- 6) ทุกแปลงในระบบเป็นลำไย — เติมชื่อพืชให้แถวที่ว่าง/ไม่ใช่ลำไย
-- ------------------------------------------------------------
update public.cultivations
set crop = 'ลำไย'
where crop is null or btrim(crop) = '' or crop not like '%ลำไย%';

commit;

